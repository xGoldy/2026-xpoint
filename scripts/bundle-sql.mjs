// Concatenates the migrations and the seed into one file that can be pasted
// into the SQL editor of a hosted Supabase project: supabase/hosted.sql
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'supabase'
const migrations = readdirSync(join(dir, 'migrations'))
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => join(dir, 'migrations', f))
const parts = [...migrations, join(dir, 'seed.sql')].map(
  (file) => `-- >>> ${file}\n${readFileSync(file, 'utf8').trim()}\n`,
)
writeFileSync(
  join(dir, 'hosted.sql'),
  `-- Generated by \`npm run db:bundle\`. Do not edit; edit the sources instead.\n\n${parts.join('\n')}`,
)
console.log(`Wrote ${join(dir, 'hosted.sql')} from ${parts.length} files`)
